function getSisenseaiTranslation(key, lang) {
    if (sisenseaiTranslations[lang] && sisenseaiTranslations[lang][key]) {
        return sisenseaiTranslations[lang][key];
    }
    if (sisenseaiTranslations.en && sisenseaiTranslations.en[key]) {
        return sisenseaiTranslations.en[key];
    }
    return null;
}

function applySisenseaiTranslations(lang) {
    console.log('Applying sisense-ai translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && key.startsWith('review.sisense-ai.')) {
            const translation = getSisenseaiTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`Applied ${count} sisense-ai translations`);
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applySisenseaiTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applySisenseaiTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applySisenseaiTranslations(currentLang);
}

