function getSunoAiTranslation(key, lang) {
    if (sunoAiTranslations[lang] && sunoAiTranslations[lang][key]) {
        return sunoAiTranslations[lang][key];
    }
    if (sunoAiTranslations.en && sunoAiTranslations.en[key]) {
        return sunoAiTranslations.en[key];
    }
    return null;
}

function applySunoAiTranslations(lang) {
    
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.suno-ai.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getSunoAiTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applySunoAiTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applySunoAiTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applySunoAiTranslations(currentLang);
}


