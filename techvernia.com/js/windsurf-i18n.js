function getWindsurfTranslation(key, lang) {
    if (windsurfTranslations[lang] && windsurfTranslations[lang][key]) {
        return windsurfTranslations[lang][key];
    }
    if (windsurfTranslations.en && windsurfTranslations[lang][key]) {
        return windsurfTranslations.en[key];
    }
    return null;
}

function applyWindsurfTranslations(lang) {
    console.log('🔥 Applying windsurf translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.windsurf.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getWindsurfTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`✅ Applied ${count} windsurf translations`);
}

window.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyWindsurfTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyWindsurfTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyWindsurfTranslations(currentLang);
}

