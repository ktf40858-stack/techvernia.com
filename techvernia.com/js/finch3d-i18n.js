function getFinch3dTranslation(key, lang) {
    return (finch3dTranslations[lang] && finch3dTranslations[lang][key]) ||
           (finch3dTranslations.en && finch3dTranslations.en[key]) || null;
}

function applyFinch3dTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.finch3d.") || key.startsWith("review.common."))) {
            const translation = getFinch3dTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

