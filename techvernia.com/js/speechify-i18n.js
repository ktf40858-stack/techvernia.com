function getSpechifyTranslation(key, lang) {
    if (speechifyTranslations[lang] && speechifyTranslations[lang][key]) {
        return speechifyTranslations[lang][key];
    }
    if (speechifyTranslations.en && speechifyTranslations.en[key]) {
        return speechifyTranslations.en[key];
    }
    return null;
}

function applySpechifyTranslations(lang) {
    
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.speechify.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getSpechifyTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    
}

