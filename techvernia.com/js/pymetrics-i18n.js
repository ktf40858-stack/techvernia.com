function getPymetricsTranslation(key, lang) {
  if (pymetricsTranslations[lang] && pymetricsTranslations[lang][key]) {
    return pymetricsTranslations[lang][key];
  }
  if (pymetricsTranslations.en && pymetricsTranslations.en[key]) {
    return pymetricsTranslations.en[key];
  }
  return null;
}

function applyPymetricsTranslations(lang) {
  console.log(`🔥 Applying pymetrics translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.pymetrics.') || key.startsWith('review.common.'))) {
      const translation = getPymetricsTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`✅ Applied ${count} pymetrics translations`);
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyPymetricsTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyPymetricsTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyPymetricsTranslations(currentLang);
}

