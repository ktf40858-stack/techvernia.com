// Language selector implementation
function initContactI18n() {
    console.log('🌍 Contact i18n initializing...');
    const currentLang = localStorage.getItem('selectedLanguage') || 'en';
    console.log('📍 Current language:', currentLang);
    applyContactTranslations(currentLang);

    // Listen for language changes
    document.addEventListener('languageChanged', (e) => {
        console.log('🔄 Language changed to:', e.detail.language);
        applyContactTranslations(e.detail.language);
    });
    console.log('✅ Contact i18n initialized successfully');
}

function applyContactTranslations(lang) {
    console.log('🔧 Applying translations for language:', lang);
    const t = contactTranslations[lang] || contactTranslations.en;

    // Update page title and meta
    document.title = t.pageTitle;
    console.log('📄 Page title updated:', t.pageTitle);
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.content = t.metaDescription;

    // Update hero section
    const heroTitle = document.querySelector('.contact-hero h1');
    const heroSubtitle = document.querySelector('.contact-hero p');
    if (heroTitle) heroTitle.textContent = t.heroTitle;
    if (heroSubtitle) heroSubtitle.textContent = t.heroSubtitle;

    // Update contact cards
    const contactCards = document.querySelectorAll('.contact-card');
    if (contactCards[0]) {
        contactCards[0].querySelector('h3').textContent = t.emailCard.title;
        contactCards[0].querySelector('p').textContent = t.emailCard.description;
    }
    if (contactCards[1]) {
        contactCards[1].querySelector('h3').textContent = t.businessCard.title;
        contactCards[1].querySelector('p').textContent = t.businessCard.description;
    }
    if (contactCards[2]) {
        contactCards[2].querySelector('h3').textContent = t.supportCard.title;
        contactCards[2].querySelector('p').textContent = t.supportCard.description;
    }
    if (contactCards[3]) {
        contactCards[3].querySelector('h3').textContent = t.socialCard.title;
        contactCards[3].querySelector('p').textContent = t.socialCard.description;
    }

    // Update form
    const formTitle = document.querySelector('.contact-form h2');
    if (formTitle) formTitle.textContent = t.formTitle;

    const nameLabel = document.querySelector('label[for="name"]');
    const emailLabel = document.querySelector('label[for="email"]');
    const subjectLabel = document.querySelector('label[for="subject"]');
    const messageLabel = document.querySelector('label[for="message"]');
    const submitBtn = document.querySelector('.submit-btn');

    if (nameLabel) nameLabel.textContent = t.formName;
    if (emailLabel) emailLabel.textContent = t.formEmail;
    if (subjectLabel) subjectLabel.textContent = t.formSubject;
    if (messageLabel) messageLabel.textContent = t.formMessage;
    if (submitBtn) submitBtn.textContent = t.formSubmit;

    // Update footer
    const footerDesc = document.querySelector('.footer-desc');
    if (footerDesc) footerDesc.textContent = t.footerDescription;

    const footerHeaders = document.querySelectorAll('.footer-links h4');
    if (footerHeaders[0]) footerHeaders[0].textContent = t.footerResources;
    if (footerHeaders[1]) footerHeaders[1].textContent = t.footerLegal;

    const copyright = document.querySelector('.copyright');
    if (copyright) copyright.textContent = t.footerCopyright;
}

// Initialize on page load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initContactI18n);
} else {
    initContactI18n();
}

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { contactTranslations, applyContactTranslations };
}
