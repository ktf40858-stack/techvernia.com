function getTabnineTranslation(key, lang) {
    if (tabnineTranslations[lang] && tabnineTranslations[lang][key]) {
        return tabnineTranslations[lang][key];
    }
    if (tabnineTranslations.en && tabnineTranslations[lang][key]) {
        return tabnineTranslations.en[key];
    }
    return null;
}

function applyTabnineTranslations(lang) {
    console.log('🔥 Applying tabnine translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.tabnine.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getTabnineTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`✅ Applied ${count} tabnine translations`);
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyTabnineTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyTabnineTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyTabnineTranslations(currentLang);
}

