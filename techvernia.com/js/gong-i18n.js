function getGongTranslation(key, lang) {
  if (gongTranslations[lang] && gongTranslations[lang][key]) {
    return gongTranslations[lang][key];
  }
  if (gongTranslations.en && gongTranslations[lang][key]) {
    return gongTranslations.en[key];
  }
  return null;
}

function applyGongTranslations(lang) {
  console.log(`Applying gong translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.gong.') || key.startsWith('review.common.'))) {
      const translation = getGongTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`Applied ${count} gong translations`);
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyGongTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyGongTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyGongTranslations(currentLang);
}

