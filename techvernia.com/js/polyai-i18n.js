function getPolyaiTranslation(key, lang) {
  if (polyaiTranslations[lang] && polyaiTranslations[lang][key]) {
    return polyaiTranslations[lang][key];
  }
  if (polyaiTranslations.en && polyaiTranslations.en[key]) {
    return polyaiTranslations.en[key];
  }
  return null;
}

function applyPolyaiTranslations(lang) {
  
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.polyai.') || key.startsWith('review.common.'))) {
      const translation = getPolyaiTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyPolyaiTranslations(lang), 200);
});

