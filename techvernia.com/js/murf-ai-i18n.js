function getMurfAiTranslation(key, lang) {
    if (murfAiTranslations[lang] && murfAiTranslations[lang][key]) {
        return murfAiTranslations[lang][key];
    }
    if (murfAiTranslations.en && murfAiTranslations.en[key]) {
        return murfAiTranslations.en[key];
    }
    return null;
}

function applyMurfAiTranslations(lang) {
    console.log('🔥 Applying murf-ai translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.murf-ai.') || key.startsWith('review.common.'))) {
            const translation = getMurfAiTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`✅ Applied ${count} murf-ai translations`);
}

window.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyMurfAiTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyMurfAiTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyMurfAiTranslations(currentLang);
}

