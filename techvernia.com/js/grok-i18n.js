function getGrokTranslation(key, lang) {
  if (grokTranslations[lang] && grokTranslations[lang][key]) {
    return grokTranslations[lang][key];
  }
  if (grokTranslations.en && grokTranslations.en[key]) {
    return grokTranslations.en[key];
  }
  return null;
}

function applyGrokTranslations(lang) {
  console.log(`🔥 Applying grok translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.grok.') || key.startsWith('review.common.'))) {
      const translation = getGrokTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`✅ Applied ${count} grok translations`);
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyGrokTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyGrokTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyGrokTranslations(currentLang);
}

