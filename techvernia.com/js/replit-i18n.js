function getReplitTranslation(key, lang) {
    if (replitTranslations[lang] && replitTranslations[lang][key]) {
        return replitTranslations[lang][key];
    }
    if (replitTranslations.en && replitTranslations[lang][key]) {
        return replitTranslations.en[key];
    }
    return null;
}

function applyReplitTranslations(lang) {
    console.log('🔥 Applying replit translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.replit.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getReplitTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`✅ Applied ${count} replit translations`);
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyReplitTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyReplitTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyReplitTranslations(currentLang);
}

