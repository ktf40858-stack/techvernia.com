function getSystranTranslation(key, lang) {
  if (systranTranslations[lang] && systranTranslations[lang][key]) {
    return systranTranslations[lang][key];
  }
  if (systranTranslations.en && systranTranslations.en[key]) {
    return systranTranslations.en[key];
  }
  return null;
}

function applySystranTranslations(lang) {
  console.log(`🔥 Applying systran translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.systran.') || key.startsWith('review.common.'))) {
      const translation = getSystranTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`✅ Applied ${count} systran translations`);
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applySystranTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applySystranTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applySystranTranslations(currentLang);
}

