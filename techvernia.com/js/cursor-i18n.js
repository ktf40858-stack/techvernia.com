// Expose cursorTranslations to window for i18n.js
window.cursorTranslations = cursorTranslations;

function getCursorTranslation(key, lang) {
    if (cursorTranslations[lang] && cursorTranslations[lang][key]) {
        return cursorTranslations[lang][key];
    }
    if (cursorTranslations.en && cursorTranslations.en[key]) {
        return cursorTranslations.en[key];
    }
    return null;
}

function applyCursorTranslations(lang) {
    console.log('🔥 Applying cursor translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.cursor.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getCursorTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`✅ Applied ${count} cursor translations`);
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyCursorTranslations(lang), 200);
});

