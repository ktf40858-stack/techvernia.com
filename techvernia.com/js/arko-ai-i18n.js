function getArkoAiTranslation(key, lang) {
    return (arkoaiTranslations[lang] && arkoaiTranslations[lang][key]) ||
           (arkoaiTranslations.en && arkoaiTranslations.en[key]) || null;
}

function applyArkoAiTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.arko-ai.") || key.startsWith("review.common."))) {
            const translation = getArkoAiTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} arko-ai translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applyArkoAiTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyArkoAiTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyArkoAiTranslations(window.i18n?.getCurrentLanguage() || "en");
}
