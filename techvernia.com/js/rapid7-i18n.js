function getRapid7Translation(key, lang) {
    return (rapid7Translations[lang] && rapid7Translations[lang][key]) ||
           (rapid7Translations.en && rapid7Translations.en[key]) || null;
}

function applyRapid7Translations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.rapid7.") || key.startsWith("review.common."))) {
            const translation = getRapid7Translation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} rapid7 translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applyRapid7Translations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyRapid7Translations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyRapid7Translations(window.i18n?.getCurrentLanguage() || "en");
}
