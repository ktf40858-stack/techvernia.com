function getGeminiTranslation(key, lang) {
  if (geminiTranslations[lang] && geminiTranslations[lang][key]) {
    return geminiTranslations[lang][key];
  }
  if (geminiTranslations.en && geminiTranslations.en[key]) {
    return geminiTranslations.en[key];
  }
  return null;
}

function applyGeminiTranslations(lang) {
  console.log(`🔥 Applying gemini translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.gemini.') || key.startsWith('review.common.'))) {
      const translation = getGeminiTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`✅ Applied ${count} gemini translations`);
}

window.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyGeminiTranslations(lang), 200);
});

