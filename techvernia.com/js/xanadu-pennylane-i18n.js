function getXanadupennylaneTranslation(key, lang) {
  if (xanadupennylaneTranslations[lang] && xanadupennylaneTranslations[lang][key]) {
    return xanadupennylaneTranslations[lang][key];
  }
  if (xanadupennylaneTranslations.en && xanadupennylaneTranslations.en[key]) {
    return xanadupennylaneTranslations.en[key];
  }
  return null;
}

function applyXanadupennylaneTranslations(lang) {
  console.log(`🔥 Applying xanadu-pennylane translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.xanadu-pennylane.') || key.startsWith('review.common.'))) {
      const translation = getXanadupennylaneTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`✅ Applied ${count} xanadu-pennylane translations`);
}

