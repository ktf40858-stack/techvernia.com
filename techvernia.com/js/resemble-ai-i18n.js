function getResembleAiTranslation(key, lang) {
    if (resembleAiTranslations[lang] && resembleAiTranslations[lang][key]) {
        return resembleAiTranslations[lang][key];
    }
    if (resembleAiTranslations.en && resembleAiTranslations.en[key]) {
        return resembleAiTranslations.en[key];
    }
    return null;
}

function applyResembleAiTranslations(lang) {
    
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.resemble-ai.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getResembleAiTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyResembleAiTranslations(lang), 200);
});

