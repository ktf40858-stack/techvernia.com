function getAdaTranslation(key, lang) {
  if (adaTranslations[lang] && adaTranslations[lang][key]) {
    return adaTranslations[lang][key];
  }
  if (adaTranslations.en && adaTranslations.en[key]) {
    return adaTranslations.en[key];
  }
  return null;
}

function applyAdaTranslations(lang) {
  
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.ada.') || key.startsWith('review.common.'))) {
      const translation = getAdaTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyAdaTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyAdaTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyAdaTranslations(currentLang);
}


