def format_tool_name(tool):
    """Format tool name for display (capitalize, replace hyphens)"""
    return tool.replace('-', ' ').title().replace(' Ai', ' AI')

def generate_i18n_file(tool_name):
    """Generate a complete i18n file for a specific HR tool"""

    formatted_name = format_tool_name(tool_name)
    const_name = tool_name.replace('-', '_').title().replace('_', '') + 'Translations'

    output = []
    output.append(f"// {formatted_name.upper()} I18N")
    output.append(f"const {tool_name.replace('-', '')}Translations = {{")

    for lang_code in ['en', 'fr', 'de', 'es', 'pt', 'zh', 'ja', 'ko', 'ar', 'hi']:
        output.append(f'  "{lang_code}": {{')

        lang_trans = TRANSLATIONS[lang_code]

        # Generate all translation keys
        for key, template in lang_trans.items():
            # Replace {tool} placeholder with actual tool name
            value = template.replace('{tool}', formatted_name)

            # Create the i18n key following the pattern: review.TOOL.key
            i18n_key = f"review.{tool_name}.{key.replace('_', '.')}"

            # Escape quotes and special characters in value
            escaped_value = value.replace('\\', '\\\\').replace('"', '\\"')

            output.append(f'    "{i18n_key}": "{escaped_value}",')

        # Remove trailing comma from last entry
        if output[-1].endswith(','):
            output[-1] = output[-1][:-1]

        output.append('  },')

    # Remove trailing comma from last language
    if output[-1].endswith(','):
        output[-1] = output[-1][:-1]

    output.append('};')
    output.append('')
    output.append('// Export')
    output.append(f'if (typeof module !== "undefined" && module.exports) {{')
    output.append(f'  module.exports = {tool_name.replace("-", "")}Translations;')
    output.append('}')

    return '\n'.join(output)

