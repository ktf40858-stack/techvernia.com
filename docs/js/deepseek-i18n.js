function getDeepseekTranslation(key, lang) {
  if (deepseekTranslations[lang] && deepseekTranslations[lang][key]) {
    return deepseekTranslations[lang][key];
  }
  if (deepseekTranslations.en && deepseekTranslations.en[key]) {
    return deepseekTranslations.en[key];
  }
  return null;
}

function applyDeepseekTranslations(lang) {
  
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.deepseek.') || key.startsWith('review.common.'))) {
      const translation = getDeepseekTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyDeepseekTranslations(lang), 200);
});

