function getCodeiumTranslation(key, lang) {
    if (codeiumTranslations[lang] && codeiumTranslations[lang][key]) {
        return codeiumTranslations[lang][key];
    }
    if (codeiumTranslations.en && codeiumTranslations.en[key]) {
        return codeiumTranslations.en[key];
    }
    return null;
}

function applyCodeiumTranslations(lang) {
    
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.codeium.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getCodeiumTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyCodeiumTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyCodeiumTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyCodeiumTranslations(currentLang);
}

