function getGlm47Translation(key, lang) {
  if (glm47Translations[lang] && glm47Translations[lang][key]) {
    return glm47Translations[lang][key];
  }
  if (glm47Translations.en && glm47Translations.en[key]) {
    return glm47Translations.en[key];
  }
  return null;
}

function applyGlm47Translations(lang) {
  
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.glm-4-7.') || key.startsWith('review.common.'))) {
      const translation = getGlm47Translation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyGlm47Translations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyGlm47Translations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyGlm47Translations(currentLang);
}


