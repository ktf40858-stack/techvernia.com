function getTestfitTranslation(key, lang) {
    return (testfitTranslations[lang] && testfitTranslations[lang][key]) ||
           (testfitTranslations.en && testfitTranslations.en[key]) || null;
}

function applyTestfitTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.testfit.") || key.startsWith("review.common."))) {
            const translation = getTestfitTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

window.addEventListener("languageChanged", e => setTimeout(() => applyTestfitTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyTestfitTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyTestfitTranslations(window.i18n?.getCurrentLanguage() || "en");
}
