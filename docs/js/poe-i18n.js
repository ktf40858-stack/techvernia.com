function getPoeTranslation(key, lang) {
  if (poeTranslations[lang] && poeTranslations[lang][key]) {
    return poeTranslations[lang][key];
  }
  if (poeTranslations.en && poeTranslations.en[key]) {
    return poeTranslations.en[key];
  }
  return null;
}

function applyPoeTranslations(lang) {
  
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.poe.') || key.startsWith('review.common.'))) {
      const translation = getPoeTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  
}

document.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyPoeTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyPoeTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyPoeTranslations(currentLang);
}


