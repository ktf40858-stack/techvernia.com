// Initialize i18n for Blog page
function initBlogI18n() {
    
    const currentLang = localStorage.getItem('selectedLanguage') || 'en';
    
    applyBlogTranslations(currentLang);

    // Listen for language changes
    document.addEventListener('languageChanged', (e) => {
        
        applyBlogTranslations(e.detail.language);
    });
    
}

function applyBlogTranslations(lang) {
    
    const t = blogTranslations[lang] || blogTranslations.en;

    // Update page title and meta
    document.title = t.pageTitle;
    const metaDesc = document.querySelector('meta[name="description"]');
    const metaKeywords = document.querySelector('meta[name="keywords"]');
    if (metaDesc) metaDesc.content = t.metaDescription;
    if (metaKeywords) metaKeywords.content = t.metaKeywords;
    

    // Hero Section
    const heroTitle = document.querySelector('.page-title');
    const heroSubtitle = document.querySelector('.page-subtitle');
    if (heroTitle) heroTitle.textContent = t.heroTitle;
    if (heroSubtitle) heroSubtitle.textContent = t.heroSubtitle;

    // Filter Buttons
    const filterBtns = document.querySelectorAll('.filter-btn');
    if (filterBtns[0]) filterBtns[0].textContent = t.filterAll;
    if (filterBtns[1]) filterBtns[1].textContent = t.filterReviews;
    if (filterBtns[2]) filterBtns[2].textContent = t.filterComparisons;
    if (filterBtns[3]) filterBtns[3].textContent = t.filterTutorials;
    if (filterBtns[4]) filterBtns[4].textContent = t.filterNews;
    if (filterBtns[5]) filterBtns[5].textContent = t.filterNetwork;

    // Featured Article
    const featuredLabel = document.querySelector('.featured-label');
    const featuredDate = document.querySelector('.blog-page-featured .blog-date');
    const featuredReadTime = document.querySelector('.blog-page-featured .blog-read-time');
    const featuredTitle = document.querySelector('.blog-page-featured .blog-title');
    const featuredExcerpt = document.querySelector('.blog-page-featured .blog-excerpt');
    const featuredAuthor = document.querySelector('.blog-page-featured .author-avatar + span');
    const featuredButton = document.querySelector('.blog-page-featured .btn-primary');

    if (featuredLabel) featuredLabel.textContent = t.featuredLabel;
    if (featuredDate) {
        featuredDate.style.display = 'none'; // Hide featured article date
    }
    if (featuredReadTime) featuredReadTime.textContent = t.featuredReadTime;
    if (featuredTitle) featuredTitle.textContent = t.featuredTitle;
    if (featuredExcerpt) featuredExcerpt.textContent = t.featuredExcerpt;
    if (featuredAuthor) featuredAuthor.textContent = t.featuredAuthor;
    if (featuredButton) featuredButton.textContent = t.featuredButton;

    // Blog Cards - Update Article Content
    const blogCards = document.querySelectorAll('.blog-page-grid .blog-card');
    

    // Array of article keys
    const articles = ['article1', 'article2', 'article3', 'article4', 'article5', 'article6', 'article7', 'article8', 'article9', 'article10', 'article11', 'article12'];

    blogCards.forEach((card, index) => {
        if (index < articles.length) {
            const articleKey = articles[index];

            // Update title
            const titleEl = card.querySelector('.blog-title');
            if (titleEl && t[`${articleKey}Title`]) {
                titleEl.textContent = t[`${articleKey}Title`];
            }

            // Update excerpt
            const excerptEl = card.querySelector('.blog-excerpt');
            if (excerptEl && t[`${articleKey}Excerpt`]) {
                excerptEl.textContent = t[`${articleKey}Excerpt`];
            }

            // Hide date element
            const dateEl = card.querySelector('.blog-date');
            if (dateEl) {
                dateEl.style.display = 'none';
            }
        }
    });

    // Blog Cards - Update "Read More" links
    const readMoreLinks = document.querySelectorAll('.blog-card .blog-link');
    readMoreLinks.forEach(link => {
        link.textContent = t.readMore + ' →';
    });

    // Update all "min read" text
    const readTimesAll = document.querySelectorAll('.blog-read-time');
    readTimesAll.forEach(readTime => {
        // Keep the number, just replace "min read"
        const timeMatch = readTime.textContent.match(/\d+/);
        if (timeMatch) {
            readTime.textContent = `${timeMatch[0]} ${t.minRead}`;
        }
    });

    // Pagination
    const prevBtn = document.querySelector('.page-btn:first-child');
    const nextBtn = document.querySelector('.page-btn:last-child');
    // Note: These might not have text content, they might use icons

    // Footer
    const footerHeaders = document.querySelectorAll('.footer-links h4');
    if (footerHeaders[0]) footerHeaders[0].textContent = t.footerCategories;
    if (footerHeaders[1]) footerHeaders[1].textContent = t.footerResources;
    if (footerHeaders[2]) footerHeaders[2].textContent = t.footerCompany;

    const copyright = document.querySelector('.copyright');
    const affiliateNotice = document.querySelector('.affiliate-notice');
    if (copyright) copyright.textContent = t.footerCopyright;
    if (affiliateNotice) affiliateNotice.textContent = t.footerAffiliateNotice;

    
}

