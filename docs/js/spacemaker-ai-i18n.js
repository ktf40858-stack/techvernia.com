function getSpacemakerAiTranslation(key, lang) {
    return (spacemakeraiTranslations[lang] && spacemakeraiTranslations[lang][key]) ||
           (spacemakeraiTranslations.en && spacemakeraiTranslations.en[key]) || null;
}

function applySpacemakerAiTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.spacemaker-ai.") || key.startsWith("review.common."))) {
            const translation = getSpacemakerAiTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

window.addEventListener("languageChanged", e => setTimeout(() => applySpacemakerAiTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applySpacemakerAiTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applySpacemakerAiTranslations(window.i18n?.getCurrentLanguage() || "en");
}
