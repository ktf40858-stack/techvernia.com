function getElevenLabsTranslation(key, lang) {
    if (elevenlabsTranslations[lang] && elevenlabsTranslations[lang][key]) {
        return elevenlabsTranslations[lang][key];
    }
    if (elevenlabsTranslations.en && elevenlabsTranslations.en[key]) {
        return elevenlabsTranslations.en[key];
    }
    return null;
}

function applyElevenLabsTranslations(lang) {
    
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.elevenlabs.') || key.startsWith('review.common.'))) {
            const translation = getElevenLabsTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    
}

document.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyElevenLabsTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyElevenLabsTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyElevenLabsTranslations(currentLang);
}


