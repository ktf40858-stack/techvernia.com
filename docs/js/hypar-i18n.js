function getHyparTranslation(key, lang) {
    return (hyparTranslations[lang] && hyparTranslations[lang][key]) ||
           (hyparTranslations.en && hyparTranslations.en[key]) || null;
}

function applyHyparTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.hypar.") || key.startsWith("review.common."))) {
            const translation = getHyparTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

window.addEventListener("languageChanged", e => setTimeout(() => applyHyparTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyHyparTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyHyparTranslations(window.i18n?.getCurrentLanguage() || "en");
}
