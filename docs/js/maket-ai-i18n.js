function getMaketAiTranslation(key, lang) {
    return (maketaiTranslations[lang] && maketaiTranslations[lang][key]) ||
           (maketaiTranslations.en && maketaiTranslations.en[key]) || null;
}

function applyMaketAiTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.maket-ai.") || key.startsWith("review.common."))) {
            const translation = getMaketAiTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

