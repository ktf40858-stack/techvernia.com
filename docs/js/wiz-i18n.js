function getWizTranslation(key, lang) {
    return (wizTranslations[lang] && wizTranslations[lang][key]) ||
           (wizTranslations.en && wizTranslations.en[key]) || null;
}

function applyWizTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.wiz.") || key.startsWith("review.common."))) {
            const translation = getWizTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

window.addEventListener("languageChanged", e => setTimeout(() => applyWizTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyWizTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyWizTranslations(window.i18n?.getCurrentLanguage() || "en");
}
