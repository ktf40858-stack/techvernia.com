function getOktaTranslation(key, lang) {
    return (oktaTranslations[lang] && oktaTranslations[lang][key]) ||
           (oktaTranslations.en && oktaTranslations.en[key]) || null;
}

function applyOktaTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.okta.") || key.startsWith("review.common."))) {
            const translation = getOktaTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    
}

window.addEventListener("languageChanged", e => setTimeout(() => applyOktaTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyOktaTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyOktaTranslations(window.i18n?.getCurrentLanguage() || "en");
}
