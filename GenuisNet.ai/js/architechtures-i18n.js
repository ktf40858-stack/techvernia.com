function getArchitechturesTranslation(key, lang) {
    return (architechturesTranslations[lang] && architechturesTranslations[lang][key]) ||
           (architechturesTranslations.en && architechturesTranslations.en[key]) || null;
}

function applyArchitechturesTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.architechtures.") || key.startsWith("review.common."))) {
            const translation = getArchitechturesTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} architechtures translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applyArchitechturesTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyArchitechturesTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyArchitechturesTranslations(window.i18n?.getCurrentLanguage() || "en");
}
