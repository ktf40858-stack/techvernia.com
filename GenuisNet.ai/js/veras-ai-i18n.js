function getVerasAiTranslation(key, lang) {
    return (verasaiTranslations[lang] && verasaiTranslations[lang][key]) ||
           (verasaiTranslations.en && verasaiTranslations.en[key]) || null;
}

function applyVerasAiTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.veras-ai.") || key.startsWith("review.common."))) {
            const translation = getVerasAiTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} veras-ai translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applyVerasAiTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyVerasAiTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyVerasAiTranslations(window.i18n?.getCurrentLanguage() || "en");
}
