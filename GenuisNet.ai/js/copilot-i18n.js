function getCopilotTranslation(key, lang) {
  if (copilotTranslations[lang] && copilotTranslations[lang][key]) {
    return copilotTranslations[lang][key];
  }
  if (copilotTranslations.en && copilotTranslations.en[key]) {
    return copilotTranslations.en[key];
  }
  return null;
}

function applyCopilotTranslations(lang) {
  console.log(`🔥 Applying copilot translations for: ${lang}`);
  let count = 0;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key && (key.startsWith('review.copilot.') || key.startsWith('review.common.'))) {
      const translation = getCopilotTranslation(key, lang);
      if (translation) {
        element.textContent = translation;
        count++;
      }
    }
  });
  console.log(`✅ Applied ${count} copilot translations`);
}

window.addEventListener('languageChanged', (e) => {
  const lang = e.detail.language;
  setTimeout(() => applyCopilotTranslations(lang), 200);
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyCopilotTranslations(currentLang);
  });
} else {
  const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
  applyCopilotTranslations(currentLang);
}

