// Fonction pour obtenir une traduction
function getCanvaAiTranslation(key, lang) {
    if (canvaaiTranslations[lang] && canvaaiTranslations[lang][key]) {
        return canvaaiTranslations[lang][key];
    }
    // Fallback à l'anglais
    if (canvaaiTranslations.en && canvaaiTranslations.en[key]) {
        return canvaaiTranslations.en[key];
    }
    return null;
}

// Appliquer les traductions canva-ai
function applyCanvaAiTranslations(lang) {
    console.log('🔥 Applying canva-ai translations for:', lang);

    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');

        // Seulement pour les clés canva-ai
        if (key && (key.startsWith('review.canva-ai.') || key.startsWith('review.common.'))) {
            const translation = getCanvaAiTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });

    console.log(`✅ Applied ${count} canva-ai translations`);
}

// Auto-appliquer quand la langue change
window.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyCanvaAiTranslations(lang), 200);
});

// Appliquer au chargement
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyCanvaAiTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyCanvaAiTranslations(currentLang);
}

console.log('✅ canva-ai i18n loaded');
