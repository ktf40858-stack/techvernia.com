function getVectraAiTranslation(key, lang) {
    return (vectraaiTranslations[lang] && vectraaiTranslations[lang][key]) ||
           (vectraaiTranslations.en && vectraaiTranslations.en[key]) || null;
}

function applyVectraAiTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.vectra-ai.") || key.startsWith("review.common."))) {
            const translation = getVectraAiTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} vectra-ai translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applyVectraAiTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyVectraAiTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyVectraAiTranslations(window.i18n?.getCurrentLanguage() || "en");
}
