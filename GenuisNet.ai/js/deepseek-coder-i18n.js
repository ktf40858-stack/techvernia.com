function getDeepSeekCoderTranslation(key, lang) {
    if (deepseekCoderTranslations[lang] && deepseekCoderTranslations[lang][key]) {
        return deepseekCoderTranslations[lang][key];
    }
    if (deepseekCoderTranslations.en && deepseekCoderTranslations[lang][key]) {
        return deepseekCoderTranslations.en[key];
    }
    return null;
}

function applyDeepSeekCoderTranslations(lang) {
    console.log('🔥 Applying deepseek-coder translations for:', lang);
    let count = 0;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && (key.startsWith('review.deepseek-coder.') || key.startsWith('review.common.') || key.startsWith('nav.'))) {
            const translation = getDeepSeekCoderTranslation(key, lang);
            if (translation) {
                element.textContent = translation;
                count++;
            }
        }
    });
    console.log(`✅ Applied ${count} deepseek-coder translations`);
}

window.addEventListener('languageChanged', (e) => {
    const lang = e.detail.language;
    setTimeout(() => applyDeepSeekCoderTranslations(lang), 200);
});

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
        applyDeepSeekCoderTranslations(currentLang);
    });
} else {
    const currentLang = window.i18n ? window.i18n.getCurrentLanguage() : 'en';
    applyDeepSeekCoderTranslations(currentLang);
}

