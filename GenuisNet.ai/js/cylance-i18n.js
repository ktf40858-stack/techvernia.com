function getCylanceTranslation(key, lang) {
    return (cylanceTranslations[lang] && cylanceTranslations[lang][key]) ||
           (cylanceTranslations.en && cylanceTranslations.en[key]) || null;
}

function applyCylanceTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.cylance.") || key.startsWith("review.common."))) {
            const translation = getCylanceTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} cylance translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applyCylanceTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applyCylanceTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applyCylanceTranslations(window.i18n?.getCurrentLanguage() || "en");
}
