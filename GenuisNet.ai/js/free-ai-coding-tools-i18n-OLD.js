function applyArticleTranslations() {
    const lang = localStorage.getItem('language') || 'en';
    const t = articleTranslations[lang] || articleTranslations.en;
    if (t.pageTitle) document.title = t.pageTitle;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && t.metaDescription) metaDesc.setAttribute('content', t.metaDescription);
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const k = el.getAttribute('data-i18n');
        if (t[k]) el.textContent = t[k];
    });
}
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyArticleTranslations);
} else { applyArticleTranslations(); }
document.addEventListener('languageChanged', applyArticleTranslations);