// Initialize i18n for AI Chatbots Category page
function initChatbotsCategoryI18n() {
    console.log('🌍 AI Chatbots Category i18n initializing...');
    const currentLang = localStorage.getItem('selectedLanguage') || 'en';
    console.log('📍 Current language:', currentLang);
    applyChatbotsCategoryTranslations(currentLang);

    // Listen for language changes
    document.addEventListener('languageChanged', (e) => {
        console.log('🔄 Language changed to:', e.detail.language);
        applyChatbotsCategoryTranslations(e.detail.language);
    });
    console.log('✅ AI Chatbots Category i18n initialized successfully');
}

function applyChatbotsCategoryTranslations(lang) {
    console.log('🔧 Applying AI Chatbots Category translations for language:', lang);
    const t = chatbotsCategoryTranslations[lang] || chatbotsCategoryTranslations.en;

    // Update page title and meta
    document.title = t.pageTitle;
    const metaDesc = document.querySelector('meta[name="description"]');
    const metaKeywords = document.querySelector('meta[name="keywords"]');
    if (metaDesc) metaDesc.content = t.metaDescription;
    if (metaKeywords) metaKeywords.content = t.metaKeywords;
    console.log('📄 Page title updated:', t.pageTitle);

    // Hero Section
    const heroTitle = document.querySelector('.category-hero h1');
    const heroDescription = document.querySelector('.category-hero p');
    if (heroTitle) heroTitle.textContent = t.heroTitle;
    if (heroDescription) {
        // Check if there's a span with data-i18n
        const span = heroDescription.querySelector('span[data-i18n]');
        if (span) {
            span.textContent = t.heroDescription;
        } else {
            heroDescription.textContent = t.heroDescription;
        }
    }

    // Stats
    const statLabels = document.querySelectorAll('.category-stat-label');
    if (statLabels[0]) statLabels[0].textContent = t.toolsReviewed;
    if (statLabels[1]) statLabels[1].textContent = t.avgRating;

    // Tool Cards - Full Review text
    const fullReviewSpans = document.querySelectorAll('.meta-item span[data-i18n="btn.review"]');
    fullReviewSpans.forEach(span => {
        span.textContent = t.fullReview;
    });

    // Country names
    const countrySpans = document.querySelectorAll('.country-name');
    countrySpans.forEach(span => {
        const dataI18n = span.getAttribute('data-i18n');
        if (dataI18n === 'country.us') {
            span.textContent = t.unitedStates;
        }
        // Add more country mappings as needed
        const currentText = span.textContent.trim();
        if (currentText === 'China') span.textContent = t.china;
        if (currentText === 'France') span.textContent = t.france;
        if (currentText === 'Germany') span.textContent = t.germany;
        if (currentText === 'United Kingdom') span.textContent = t.unitedKingdom;
    });

    // Footer
    const footerHeaders = document.querySelectorAll('.footer-links h4');
    if (footerHeaders[0]) footerHeaders[0].textContent = t.footerCategories;
    if (footerHeaders[1]) footerHeaders[1].textContent = t.footerResources;
    if (footerHeaders[2]) footerHeaders[2].textContent = t.footerCompany;

    const copyright = document.querySelector('.copyright');
    if (copyright) copyright.textContent = t.footerCopyright;

    console.log('✅ AI Chatbots Category translations applied successfully');
}

// Initialize on page load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initChatbotsCategoryI18n);
} else {
    initChatbotsCategoryI18n();
}

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { chatbotsCategoryTranslations, applyChatbotsCategoryTranslations };
}
