function getSnykTranslation(key, lang) {
    return (snykTranslations[lang] && snykTranslations[lang][key]) ||
           (snykTranslations.en && snykTranslations.en[key]) || null;
}

function applySnykTranslations(lang) {
    let count = 0;
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key && (key.startsWith("review.snyk.") || key.startsWith("review.common."))) {
            const translation = getSnykTranslation(key, lang);
            if (translation) { el.textContent = translation; count++; }
        }
    });
    console.log(`Applied ${count} snyk translations`);
}

window.addEventListener("languageChanged", e => setTimeout(() => applySnykTranslations(e.detail.language), 200));

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => applySnykTranslations(window.i18n?.getCurrentLanguage() || "en"));
} else {
    applySnykTranslations(window.i18n?.getCurrentLanguage() || "en");
}
