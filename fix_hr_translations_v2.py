def fix_hr_i18n_file_v2(tool_name):
    """
    Corrige les traductions i18n pour un outil HR (version 2)
    """
    file_path = os.path.join("GenuisNet.ai", "js", f"{tool_name}-i18n.js")

    if not os.path.exists(file_path):
        print(f"[ERREUR] Fichier non trouve: {file_path}")
        return False

    # Lire le fichier
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Compter les corrections
    corrections_count = 0
    original_content = content

    # Pour chaque langue
    for lang in ["zh", "ja", "ko", "ar", "hi"]:
        # Trouver la section de la langue dans le fichier
        lang_section_start = f'"{lang}": {{'
        if lang_section_start not in content:
            continue

        # Pour chaque traduction
        for english_quoted, translated_quoted in COMMON_TRANSLATIONS[lang].items():
            # Rechercher et remplacer
            if english_quoted in content:
                content = content.replace(english_quoted, translated_quoted)
                corrections_count += 1

